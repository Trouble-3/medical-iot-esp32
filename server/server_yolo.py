import serial
import cv2
import numpy as np
from ultralytics import YOLO

# --- НАСТРОЙКИ ---
PORT = 'COM6'          # Твой COM-порт
BAUD = 115200          # Скорость (должна совпадать с Arduino)
MODEL_PATH = 'best.pt' # Файл модели

# Загружаем твою обученную модель классификации
try:
    model = YOLO(MODEL_PATH)
    print(f"[ИИ] Модель {MODEL_PATH} успешно загружена!")
except Exception as e:
    print(f"[ОШИБКА] Не удалось загрузить модель: {e}")
    exit()

# Интерактивная база данных лекарств
# ВАЖНО: Ключи (ergoferon, aspirin) должны строго совпадать с названиями твоих папок из датасета!
medicines_db = {
    "ergoferon": {
        "info": "Эргоферон - комплексный препарат, обладающий противовирусным, иммуномодулирующим и антигистаминным (противоаллергическим) действием. Эффективен при лечении гриппа и ОРВИ, так как не только борется с вирусом, но и снимает отек слизистых оболочек.",
        "dose": "В первый день: 8 таблеток по схеме. Сначала по 1 таб. каждые 30 минут в течение 2 часов (всего 5 штук), затем еще 3 таблетки через равные промежутки времени до конца дня. Со второго дня: по 1 таблетке 3 раза в день до полного выздоровления.",
        "q": "Есть ли у вас врожденная лактазная недостаточность или аллергия на компоненты препарата?"
    },
    "angidak": {
        "info": "Ангидак - это местный противовоспалительный препарат в форме спрея (НПВС). Он быстро проникает в воспаленные ткани горла, снимает боль, отек и чувство жжения. Оказывает также антисептическое действие против широкого спектра микроорганизмов.",
        "dose": "Взрослым назначают по 4-8 распылений каждые 1,5-3 часа в зависимости от интенсивности боли. Детям от 6 до 12 лет - по 4 распыления. Перед применением рекомендуется прополоскать рот водой. Курс лечения обычно составляет от 3 до 7 дней.",
        "q": "Есть ли у вас аллергия на нестероидные противовоспалительные препараты (например, аспирин) или бронхиальная астма?"
    },
    "miramistin": {
        "info": "Мирамистин - мощный антисептик широкого спектра действия. Он уничтожает бактерии, вирусы и грибки, не повреждая при этом здоровые клетки. Препарат стимулирует местный иммунитет и ускоряет процесс заживления тканей, не имеет вкуса и запаха.",
        "dose": "При лечении ангины или фарингита проводить орошение горла путем 3-4 нажатий на насадку-распылитель. Процедуру повторять 3-4 раза в сутки. После применения желательно не принимать пищу и не пить воду в течение 30-60 минут для сохранения эффекта.",
        "q": "Замечали ли вы ранее жжение при контакте препарата с кожей или слизистыми, которое не проходит в течение минуты?"
    }
}

try:
    ser = serial.Serial(PORT, BAUD, timeout=1)
    print(f"[СВЯЗЬ] Порт {PORT} успешно открыт. Ожидание команды от ESP32-S3...\n")
except Exception as e:
    print(f"[ОШИБКА] Не удалось открыть порт {PORT}: {e}")
    print("Проверь USB-кабель и закрой Serial Monitor в Arduino IDE!")
    exit()

while True:
    raw_line = ser.readline()
    try:
        line = raw_line.decode(errors='ignore').strip()
    except:
        continue

    # 1. Сценарий: Получение и обработка фотографии
    if line == "START_IMAGE":
        try:
            size_line = ser.readline().decode(errors='ignore').strip()
            image_size = int(size_line)
            raw_data = ser.read(image_size)
            nparr = np.frombuffer(raw_data, np.uint8)
            img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
            
            if img is not None:
                results = model(img, verbose=False)

                result = results[0]
                
                if result.probs is not None:
                    # Теперь берем данные из объекта result
                    class_id = int(result.probs.top1)
                    confidence = float(result.probs.top1conf)
                    class_name = result.names[class_id]
                    
                    print("-" * 30)
                    print(f"[ИИ] Класс: {class_name}")
                    print(f"[ИИ] Уверенность: {confidence:.4f} ({confidence*100:.1f}%)")
                    
                    # Логика принятия решения
                    if class_name == "background":
                        ser.write("Объект не распознан. Попробуйте еще раз.\n".encode('utf-8'))
                        print("[СТАТУС] Отклонено: Вижу только фон.")
                    
                    elif confidence < 0.85:
                        msg = f"Это я не знаю \n"
                        ser.write(msg.encode('utf-8'))
                        print(f"[СТАТУС] Сомнение: Слишком низкий порог.")
                    
                    elif class_name in medicines_db:
                        data = medicines_db[class_name]
                        response = f"{data['info']} {data['dose']} {data['q']}"
                        ser.write((response + "\n").encode('utf-8'))
                        print(f"[СТАТУС] Одобрено: Данные отправлены.")
                    
                        print("-" * 30)
                    else:
                        ser.write("Объект распознан, но описания нет в базе.\n".encode('utf-8'))
        except Exception as e:
            print(f"Ошибка: {e}")

    # 2. Сценарий: Обработка интерактивного ответа Да/Нет от кнопок ESP32
    if "USER_ANSWER" in line:
        print(f"[ИНТЕРФЕЙС] Получен ответ от пользователя: {line}")
        
        # Если пользователь нажал кнопку ДА
        if "YES" in line:
            feedback = "ВНИМАНИЕ! Не принимайте это лекарство. Опасно!"
        # Если пользователь нажал кнопку НЕТ
        else:
            feedback = "Хорошо. Принимайте согласно инструкции."
            
        ser.write((feedback + "\n").encode('utf-8'))
        print(f"[ОТВЕТ] Отправлен финальный вердикт: {feedback}")

ser.close()
